// Generates src/environments/environment.ts from process.env before serve/build.
// Locally, values come from .env.local; on Vercel they come from the platform's env vars.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = dirname(dirname(fileURLToPath(import.meta.url)));
const envLocalPath = join(rootDir, '.env.local');

if (existsSync(envLocalPath)) {
  for (const line of readFileSync(envLocalPath, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }
    const separatorIndex = trimmed.indexOf('=');
    if (separatorIndex === -1) {
      continue;
    }
    const key = trimmed.slice(0, separatorIndex).trim();
    const value = trimmed.slice(separatorIndex + 1).trim();
    if (!(key in process.env)) {
      process.env[key] = value;
    }
  }
}

const requiredKeys = ['SUPABASE_URL', 'SUPABASE_ANON_KEY'];
for (const key of requiredKeys) {
  if (!process.env[key]) {
    throw new Error(
      `Missing required env var: ${key}. Set it in .env.local (local) or in the Vercel project settings.`,
    );
  }
}

const outDir = join(rootDir, 'src', 'environments');
mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, 'environment.ts'),
  `// Auto-generated by scripts/generate-env.mjs — do not edit, do not commit.
export const environment = {
  supabaseUrl: '${process.env.SUPABASE_URL}',
  supabaseAnonKey: '${process.env.SUPABASE_ANON_KEY}',
};
`,
);

console.log('Generated src/environments/environment.ts');
